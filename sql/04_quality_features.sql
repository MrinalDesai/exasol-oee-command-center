-- Step 4 features: the machine's condition just before each shift starts, and
-- whether that shift turned out bad at end-of-line inspection (scrap > 7%).
-- Column list must match oee/quality.py QUALITY_FEATURES.
OPEN SCHEMA OEE;

CREATE OR REPLACE VIEW V_QUALITY_TRAINING AS
WITH shifts AS (
    SELECT MACHINE_ID, SHIFT_START, SHIFT_END, TOTAL_COUNT, GOOD_COUNT,
           (TOTAL_COUNT - GOOD_COUNT) * 1.0 / NULLIF(TOTAL_COUNT, 0) AS SCRAP_RATE,
           LAG((TOTAL_COUNT - GOOD_COUNT) * 1.0 / NULLIF(TOTAL_COUNT, 0))
               OVER (PARTITION BY MACHINE_ID ORDER BY SHIFT_START)    AS PREV_SCRAP
    FROM SHIFT_PRODUCTION
),
before_shift AS (
    SELECT s.MACHINE_ID, s.SHIFT_START, s.SHIFT_END, s.TOTAL_COUNT, s.GOOD_COUNT, s.SCRAP_RATE, s.PREV_SCRAP,
           f.READING_TS, f.TOOL_WEAR_MIN, f.VIB_AVG_6H, f.TEMP_DIFF_AVG_6H, f.TORQUE_RATIO, f.POWER_AVG_6H,
           f.IS_MILL, f.IS_LATHE, f.IS_PRESS, f.IS_PACKER,
           ROW_NUMBER() OVER (PARTITION BY s.MACHINE_ID, s.SHIFT_START ORDER BY f.READING_TS DESC) AS RN
    FROM shifts s
    JOIN V_FEATURES f
      ON  f.MACHINE_ID = s.MACHINE_ID
      AND f.READING_TS <  s.SHIFT_START
      AND f.READING_TS >= ADD_HOURS(s.SHIFT_START, -3)
    WHERE s.TOTAL_COUNT >= 50
)
SELECT MACHINE_ID, SHIFT_START, SHIFT_END, READING_TS, TOTAL_COUNT, GOOD_COUNT, SCRAP_RATE,
       TOOL_WEAR_MIN, VIB_AVG_6H, TEMP_DIFF_AVG_6H, TORQUE_RATIO, POWER_AVG_6H,
       COALESCE(PREV_SCRAP, 0.0)                         AS PREV_SCRAP_RATE,
       IS_MILL, IS_LATHE, IS_PRESS, IS_PACKER,
       CASE WHEN SCRAP_RATE > 0.07 THEN 1 ELSE 0 END    AS LABEL_BAD_SHIFT
FROM before_shift
WHERE RN = 1;
