-- Step 3, part 1: four store inventory systems read as one.
--
-- Each store keeps stock in its own system and layout: SAP at the Pune and
-- Bengaluru plants, Tally at Chennai, a WMS with bin locations at the Hyderabad
-- warehouse. Part numbers are written three ways (as is, lower case, underscores).
-- V_STORE_STOCK puts all four into one shape; SPARE_PARTS is refreshed from it.
OPEN SCHEMA OEE;

CREATE OR REPLACE VIEW V_STORE_STOCK AS
SELECT 'PNQ' AS LOCATION_ID, 'SAP_PNQ.MARD' AS SOURCE_SYSTEM, CAST(NULL AS VARCHAR(16)) AS BIN_LOCATION,
       UPPER(TRIM(MATNR)) AS PART_NO, LABST AS ON_HAND, EISBE AS REORDER_POINT, PLIFZ AS LEAD_TIME_DAYS,
       VERPR AS UNIT_COST_INR
FROM SAP_PNQ.MARD
UNION ALL
SELECT 'BLR', 'SAP_BLR.MARD', CAST(NULL AS VARCHAR(16)),
       UPPER(TRIM(MATNR)), LABST, EISBE, PLIFZ, VERPR
FROM SAP_BLR.MARD
UNION ALL
SELECT 'CHN', 'TALLY_CHN.STOCK_SUMMARY', CAST(NULL AS VARCHAR(16)),
       UPPER(TRIM(ITEM_NAME)), CLOSING_QTY, REORDER_LEVEL, LEAD_DAYS, RATE
FROM TALLY_CHN.STOCK_SUMMARY
UNION ALL
SELECT 'HYD', 'WMS_HYD.INVENTORY', BIN_LOCATION,
       REPLACE(UPPER(TRIM(SKU)), '_', '-'), QTY_AVAILABLE, MIN_QTY, LEAD_TIME_D, UNIT_COST
FROM WMS_HYD.INVENTORY;

TRUNCATE TABLE SPARE_PARTS;

INSERT INTO SPARE_PARTS (PLANT_ID, PART_NO, ON_HAND, REORDER_POINT, LEAD_TIME_DAYS, UNIT_COST_INR)
SELECT LOCATION_ID, PART_NO, ON_HAND, REORDER_POINT, LEAD_TIME_DAYS, UNIT_COST_INR
FROM V_STORE_STOCK;
